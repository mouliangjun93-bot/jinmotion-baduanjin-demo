import {readFile,mkdir,writeFile} from 'node:fs/promises';
import {gzipSync} from 'node:zlib';
import {createHash} from 'node:crypto';
const root=new URL('./dist/vendor/mediapipe/',import.meta.url);
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const assets=[];
await mkdir(new URL('packed/',root),{recursive:true});
for(const [id,path] of [['wasm','wasm/vision_wasm_internal.wasm'],['model','pose_landmarker_full.task'],['loader','wasm/vision_wasm_internal.js']]){
 const raw=await readFile(new URL(path,root)),packed=gzipSync(raw,{level:9}),chunks=[];
 for(let start=0;start<packed.length;start+=262144){const bytes=packed.subarray(start,start+262144),hash=sha(bytes),name=`${id}-${chunks.length}-${hash.slice(0,16)}.bin`;await writeFile(new URL(`packed/${name}`,root),bytes);chunks.push({path:`vendor/mediapipe/packed/${name}`,size:bytes.length,sha256:hash})}
 assets.push({id,size:raw.length,sha256:sha(raw),chunks});
}
await writeFile(new URL('./dist/pose-assets.js',import.meta.url),`// Generated by pack-pose-assets.js. Content-addressed gzip chunks.\nexport const POSE_ASSETS=${JSON.stringify(assets,null,2)};\n`);
console.log(JSON.stringify({original:assets.reduce((s,a)=>s+a.size,0),download:assets.flatMap(a=>a.chunks).reduce((s,c)=>s+c.size,0),chunks:assets.flatMap(a=>a.chunks).length}));
